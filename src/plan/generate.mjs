// Narration pace of the shipped VO register, measured on rendered spools:
// ~156 words per minute. Used for the duration estimate only; the renderer
// retimes each step to the real wav (see CONTRACTS.md "Render layer inputs").
export const WORDS_PER_SECOND = 2.6;
// Per-chapter settle the renderer holds after the narration ends.
const CHAPTER_SETTLE_SECONDS = 0.6;

export const DURATION_MIN_SECONDS = 45;
export const DURATION_MAX_SECONDS = 120;
export const CHAPTER_MIN = 3;
export const CHAPTER_MAX = 6;

// The acceptance shape: a plan a reviewer can act on always says what exists,
// how it will be built, what is uncertain, and what it needs from them.
