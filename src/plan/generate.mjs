// Plan Spool narration + steps generator.
//
// Turns a validated packet (plan.json + evidence.json) into `plan.script.json`:
// an ordered narration outline, one visual source per chapter, and the decision
// card. From that one artifact both authoring paths are driven — a generated
// `steps.mjs` (scripted) and the `POST /step` bodies of a live session.
//
// Two rules shape everything here:
//
// 1. The generator never invents a claim. Author sentences are copied verbatim;
//    the generator only adds fixed lead-ins that carry no facts. Every chapter
//    records the packet paths it was built from (`sources`), and the linter
//    resolves each one, so an invented claim fails as a lint error rather than
//    reaching a reviewer.
// 2. It is deterministic. The same packet and style always produce the same
//    bytes, so a regenerated script diffs cleanly and a review is repeatable.
//
// See CONTRACTS.md "Plan Spools" → "plan.script.json".

